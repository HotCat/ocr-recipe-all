def normalize_language(language: str | None) -> str:
    if language in SUPPORTED_LANGUAGES:
        return str(language)
    return "en"


def set_language(language: str | None) -> None:
    global _language
    _language = normalize_language(language)


def current_language() -> str:
    return _language


def language_name(language: str | None) -> str:
    normalized = normalize_language(language)
    return tr(f"language.{normalized}", default=normalized)


def tr(key: str, default: str | None = None, **kwargs: Any) -> str:
    template = TRANSLATIONS.get(_language, {}).get(key)
    if template is None:
        template = TRANSLATIONS["en"].get(key, default if default is not None else key)
    return template.format(**kwargs) if kwargs else template


def category_label(category: str) -> str:
    return tr(f"category.{category}", default=category)


def node_type_label(type_name: str, default: str) -> str:
    return tr(f"node.{type_name}", default=default)


def node_label(node: Any, default: str | None = None) -> str:
    title = str(getattr(node, "title", ""))
    fallback = default if default is not None else title
    translated = tr(f"node.instance.{getattr(node, 'node_id', '')}", default="")
    if translated:
        return translated
    if default is not None and title and title != default:
        return title
    type_name = str(getattr(node, "type_name", ""))
    return node_type_label(type_name, fallback)


def port_label(name: str) -> str:
    return tr(f"port.{name}", default=name)


def param_label(name: str) -> str:
    return tr(f"param.{name}", default=name.replace("_", " ").title())
